// ---------------- 抽牌与总结 ----------------
export interface DrawnCard {
  card: TarotCard
  reversed: boolean
}

/** 洗牌（Fisher–Yates），返回卡片序号列表 */
export function shuffle(): number[] {
  const idx = TAROT_CARDS.map((_, i) => i)
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[idx[i], idx[j]] = [idx[j], idx[i]]
  }
  return idx
}

/** 从洗好的牌里抽 n 张（含正逆位） */
export function draw(shuffled: number[], n: number): DrawnCard[] {
  return shuffled.slice(0, n).map((i) => ({ card: TAROT_CARDS[i], reversed: Math.random() < 0.5 }))
}

/** 整体总结：按正逆位比例 + 大阿卡纳占比给白话结论 */
export function summarize(drawn: DrawnCard[]): string {
  const total = drawn.length
  const upright = drawn.filter((d) => !d.reversed).length
  const majors = drawn.filter((d) => d.card.suit === 'major').length
  const parts: string[] = []

  const ratio = upright / total
  if (ratio >= 0.7) parts.push('整体偏顺，多数牌为正位，事情大概率朝着积极的方向发展')
  else if (ratio <= 0.3) parts.push('逆位偏多，提示近期阻力和内心的功课较多，宜放慢脚步、多向内看')
  else parts.push('正逆位相当，事情处于波动与拉扯之中，好坏参半、需要主动把握')

  const mRatio = majors / total
  if (mRatio >= 0.5) parts.push('大阿卡纳占比高，这件事对你的影响较为深远，不是一时的小插曲')
  else parts.push('以小阿卡纳为主，更多反映日常事务与人际互动，属于近期的具体状况')

  return parts.join('；') + '。'
}
