// ---------------- 小阿卡纳（56） ----------------
const NUM_ZH = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十']
const COURT_ZH = ['', '侍从', '骑士', '王后', '国王']
const COURT_EN = ['', 'Page', 'Knight', 'Queen', 'King']
const NUM_EN = ['', 'Ace', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten']

type MinorEntry = [num: number, keywords: string[], upright: string[], reversed: string[]]

function minor(suit: Exclude<Suit, 'major'>, entry: MinorEntry): TarotCard {
  const [num, keywords, upright, reversed] = entry
  const zh = num <= 10 ? `${SUIT_ZH[suit]}${NUM_ZH[num]}` : `${SUIT_ZH[suit]}${COURT_ZH[num - 10]}`
  const en = num <= 10 ? `${NUM_EN[num]} of ${SUIT_EN[suit]}` : `${COURT_EN[num - 10]} of ${SUIT_EN[suit]}`
  return { suit, num, nameZh: zh, nameEn: en, keywords, upright, reversed }
}

