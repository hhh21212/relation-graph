export function computeCeZi(char: string): CeZiResult | null {
  const ch = char.trim().charAt(0)
  if (!ch) return null

  if (DICT[ch]) {
    return { char: ch, ji: DICT[ch].ji, text: DICT[ch].text, estimated: false }
  }

  // 未收录字：按笔画奇偶 + 是否估算给通用断法
  const strokes = charStrokes(ch)
  const ji: CeZiResult['ji'] = strokes % 2 === 0 ? '吉' : '中'
  const text =
    ji === '吉'
      ? `「${ch}」共 ${strokes} 画，笔画为偶、有双全之象。所问之事多主平稳顺遂，宜循序渐进。`
      : `「${ch}」共 ${strokes} 画，笔画为奇、有独行之意。所问之事宜谨慎谋定，事在人为。`

  return { char: ch, ji, text, estimated: hasUnknownChar(ch) }
}
