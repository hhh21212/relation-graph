export const STROKES: Record<string, number> = { ...SURNAMES, ...NAME_CHARS, ...COMMON_CHARS }

/** 单字笔画（未收录的汉字按 10 画估算；拉丁/数字按 1 画） */
export function charStrokes(ch: string): number {
  if (STROKES[ch] != null) return STROKES[ch]
  const code = ch.charCodeAt(0)
  if (code >= 0x4e00 && code <= 0x9fff) return 10 // 未收录的汉字，估算
  return 1
}

/** 一串字的笔画总和 */
export function totalStrokes(s: string): number {
  let sum = 0
  for (const ch of s) sum += charStrokes(ch)
  return sum
}

/** 是否含未收录的汉字（用于提示「估算」） */
export function hasUnknownChar(s: string): boolean {
  return [...s].some(
    (ch) => STROKES[ch] == null && ch.charCodeAt(0) >= 0x4e00 && ch.charCodeAt(0) <= 0x9fff,
  )
}
