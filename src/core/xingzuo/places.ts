export const PLACES: Place[] = [
  ...CN.map(([name, lat, lng]) => ({ name, lat, lng, tz: 8 } as Place)),
  ...WORLD.map(([name, lat, lng]) => ({ name, lat, lng } as Place)),
]

export const DEFAULT_PLACE: Place = PLACES[0]

/** 时区算法：经度 ÷ 15°（每 15° 一个时区，东经为正），四舍五入。 */
export function tzOfLng(lng: number): number {
  return Math.round(lng / 15)
}

/** 某地点的时区：有覆盖值（中国统一 +8）用覆盖值，否则用经度算法。 */
export function tzOfPlace(p: Place): number {
  return p.tz ?? tzOfLng(p.lng)
}

/** 出生地文本 → 地点（精确 / 包含匹配），找不到返回 null。 */
export function resolvePlace(name?: string | null): Place | null {
  if (!name?.trim()) return null
  const bp = name.trim()
  const hit = PLACES.find((p) => p.name === bp)
  if (hit) return hit
  return PLACES.find((p) => bp.includes(p.name) || p.name.includes(bp)) ?? null
}

/** 时区 → 可读标签（UTC+8 / UTC-5 / UTC+5:30）。 */
export function tzLabel(tz: number): string {
  const sign = tz >= 0 ? '+' : '-'
  const abs = Math.abs(tz)
  const h = Math.floor(abs)
  const m = Math.round((abs - h) * 60)
  return m === 0 ? `UTC${sign}${h}` : `UTC${sign}${h}:${String(m).padStart(2, '0')}`
}
