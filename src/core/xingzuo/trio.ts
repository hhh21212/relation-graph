function synthesis(sun: number, moon: number, rising: number): string {
  const e = [SIGNS[sun].element, SIGNS[moon].element, SIGNS[rising].element]
  if (e[0] === e[1] && e[1] === e[2]) {
    return `太阳、月亮、上升同属${e[0]}象，内外高度一致、表里如一，给人很「统一」的感觉。`
  }
  if (e[0] === e[1]) {
    return `太阳与月亮同属${e[0]}象，内在自我与情感需求一致；但上升${e[2]}是给人的外在形象，别人眼里的你更偏${e[2]}象。`
  }
  if (e[0] === e[2]) {
    return `太阳与上升同属${e[0]}象，外在表现与核心自我一致；月亮${e[1]}是内心情绪层，需要被读懂与照顾。`
  }
  if (e[1] === e[2]) {
    return `月亮与上升同属${e[1]}象，情感与外在形象一致；太阳${e[0]}是更核心的自我，熟悉之后才会露出来。`
  }
  return `太阳${e[0]}、月亮${e[1]}、上升${e[2]}各居一象，层次分明，是「越相处越有惊喜」的类型。`
}

export function trioReading(sun: number, moon: number, rising: number): TrioReading {
  return {
    heading: `${SIGNS[sun].name}太阳 × ${SIGNS[moon].name}月亮 × ${SIGNS[rising].name}上升`,
    sun: SUN_LINE[sun],
    moon: MOON_LINE[moon],
    rising: RISING_LINE[rising],
    synthesis: synthesis(sun, moon, rising),
  }
}
